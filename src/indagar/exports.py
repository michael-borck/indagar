from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .models import utc_now


class ExportError(Exception):
    """A requested export could not be produced."""


@dataclass(frozen=True)
class Block:
    kind: str
    text: str = ""
    level: int = 0
    rows: tuple[tuple[str, ...], ...] = ()


def _plain(value: str) -> str:
    value = re.sub(
        r"\[([^\]]+)\]\(([^)\s]+)\)",
        lambda match: (
            match.group(1)
            if match.group(2) in match.group(1)
            else f"{match.group(1)} ({match.group(2)})"
        ),
        value,
    )
    value = re.sub(r"\*\*([^*]+)\*\*", r"\1", value)
    value = re.sub(r"\*([^*]+)\*", r"\1", value)
    return value.replace("`", "").strip()


def _split_row(line: str) -> tuple[str, ...]:
    value = line.strip()
    if value.startswith("|"):
        value = value[1:]
    if value.endswith("|"):
        value = value[:-1]
    cells: list[str] = []
    current = ""
    escaped = False
    for char in value:
        if escaped:
            current += char
            escaped = False
        elif char == "\\":
            escaped = True
        elif char == "|":
            cells.append(_plain(current))
            current = ""
        else:
            current += char
    cells.append(_plain(current))
    return tuple(cells)


def _is_separator(line: str) -> bool:
    cells = _split_row(line)
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells)


def parse_markdown(markdown: str) -> list[Block]:
    lines = str(markdown or "").replace("\r\n", "\n").split("\n")
    blocks: list[Block] = []
    paragraph: list[str] = []
    index = 0

    def flush() -> None:
        if paragraph:
            blocks.append(Block("paragraph", _plain(" ".join(paragraph))))
            paragraph.clear()

    while index < len(lines):
        line = lines[index].strip()
        if not line:
            flush()
            index += 1
            continue

        if line.startswith("|") and index + 1 < len(lines) and _is_separator(lines[index + 1]):
            flush()
            rows: list[tuple[str, ...]] = []
            cursor = index
            while cursor < len(lines) and lines[cursor].strip().startswith("|"):
                rows.append(_split_row(lines[cursor]))
                cursor += 1
            if len(rows) >= 2:
                blocks.append(Block("table", rows=tuple(rows[:1] + rows[2:])))
            index = cursor
            continue

        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading:
            flush()
            blocks.append(Block("heading", _plain(heading.group(2)), level=len(heading.group(1))))
            index += 1
            continue

        if line.startswith("> "):
            flush()
            blocks.append(Block("quote", _plain(line[2:])))
            index += 1
            continue

        if line.startswith("- "):
            flush()
            blocks.append(Block("bullet", _plain(line[2:])))
            index += 1
            continue

        ordered = re.match(r"^\d+\.\s+(.*)$", line)
        if ordered:
            flush()
            blocks.append(Block("number", _plain(ordered.group(1))))
            index += 1
            continue

        paragraph.append(line)
        index += 1

    flush()
    return blocks


def write_docx(markdown: str, path: Path) -> Path:
    try:
        from docx import Document
    except ImportError as exc:
        raise ExportError("Install python-docx to export DOCX files.") from exc

    blocks = parse_markdown(markdown)
    document = Document()
    document.core_properties.title = next(
        (block.text for block in blocks if block.kind == "heading" and block.level == 1),
        "Indagar research report",
    )
    document.core_properties.comments = f"Generated by Indagar on {utc_now()}"

    for block in blocks:
        if block.kind == "heading":
            document.add_heading(block.text, level=min(block.level, 4))
        elif block.kind == "paragraph":
            document.add_paragraph(block.text)
        elif block.kind == "bullet":
            document.add_paragraph(block.text, style="List Bullet")
        elif block.kind == "number":
            document.add_paragraph(block.text, style="List Number")
        elif block.kind == "quote":
            paragraph = document.add_paragraph(block.text)
            paragraph.paragraph_format.left_indent = 360000
            if paragraph.runs:
                paragraph.runs[0].italic = True
        elif block.kind == "table" and block.rows:
            columns = max(len(row) for row in block.rows)
            table = document.add_table(rows=len(block.rows), cols=columns)
            table.style = "Table Grid"
            for row_index, row in enumerate(block.rows):
                for column_index, value in enumerate(row):
                    cell = table.cell(row_index, column_index)
                    cell.text = value
                    if row_index == 0:
                        for paragraph in cell.paragraphs:
                            for run in paragraph.runs:
                                run.bold = True

    path.parent.mkdir(parents=True, exist_ok=True)
    document.save(str(path))
    return path


def write_pdf(markdown: str, path: Path) -> Path:
    try:
        from xml.sax.saxutils import escape

        from reportlab.lib import colors
        from reportlab.lib.pagesizes import LETTER, landscape
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.platypus import (
            Paragraph,
            SimpleDocTemplate,
            Spacer,
            Table,
            TableStyle,
        )
    except ImportError as exc:
        raise ExportError("Install reportlab to export PDF files.") from exc

    blocks = parse_markdown(markdown)
    max_columns = max(
        (len(block.rows[0]) for block in blocks if block.kind == "table" and block.rows),
        default=0,
    )
    page_size = landscape(LETTER) if max_columns > 4 else LETTER
    path.parent.mkdir(parents=True, exist_ok=True)
    document = SimpleDocTemplate(
        str(path),
        pagesize=page_size,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36,
        title="Indagar research report",
    )

    styles = getSampleStyleSheet()
    body = ParagraphStyle(
        "IndagarBody",
        parent=styles["BodyText"],
        fontSize=9.5,
        leading=13,
        splitLongWords=1,
    )
    heading_styles = {
        1: ParagraphStyle("IndagarH1", parent=styles["Heading1"], fontSize=18, leading=22),
        2: ParagraphStyle("IndagarH2", parent=styles["Heading2"], fontSize=14, leading=18),
        3: ParagraphStyle("IndagarH3", parent=styles["Heading3"], fontSize=11.5, leading=15),
    }
    quote_style = ParagraphStyle(
        "IndagarQuote",
        parent=body,
        leftIndent=14,
        textColor=colors.HexColor("#475467"),
        fontName="Helvetica-Oblique",
    )
    cell_style = ParagraphStyle(
        "IndagarCell",
        parent=body,
        fontSize=7,
        leading=9,
        splitLongWords=1,
    )
    header_style = ParagraphStyle(
        "IndagarHeader",
        parent=cell_style,
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#344054"),
    )
    bullet_style = ParagraphStyle(
        "IndagarBullet",
        parent=body,
        leftIndent=12,
        bulletIndent=0,
    )

    story = []
    for block in blocks:
        if block.kind == "heading":
            style = heading_styles.get(block.level, heading_styles[3])
            story.append(Paragraph(escape(block.text), style))
            story.append(Spacer(1, 5))
        elif block.kind == "paragraph":
            story.append(Paragraph(escape(block.text), body))
            story.append(Spacer(1, 5))
        elif block.kind in {"bullet", "number"}:
            story.append(Paragraph(escape(block.text), bullet_style, bulletText="•"))
        elif block.kind == "quote":
            story.append(Paragraph(escape(block.text), quote_style))
            story.append(Spacer(1, 5))
        elif block.kind == "table" and block.rows:
            columns = max(len(row) for row in block.rows)
            width = (document.width / columns) if columns else document.width
            data = []
            for row_index, row in enumerate(block.rows):
                style = header_style if row_index == 0 else cell_style
                data.append(
                    [Paragraph(escape(value), style) for value in row]
                    + [Paragraph("", style)] * (columns - len(row))
                )
            table = Table(data, colWidths=[width] * columns, repeatRows=1)
            table.setStyle(
                TableStyle(
                    [
                        ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D0D5DD")),
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F2F4F7")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("LEFTPADDING", (0, 0), (-1, -1), 3),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 3),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ]
                )
            )
            story.append(table)
            story.append(Spacer(1, 8))

    document.build(story)
    return path


def export_file(markdown_path: Path, kind: str) -> Path:
    if not markdown_path.exists():
        raise ExportError("Markdown source not found.")
    suffix = f".{kind}"
    output = markdown_path.with_suffix(suffix)
    if output.exists() and output.stat().st_mtime >= markdown_path.stat().st_mtime:
        return output
    markdown = markdown_path.read_text(encoding="utf-8")
    if kind == "docx":
        return write_docx(markdown, output)
    if kind == "pdf":
        return write_pdf(markdown, output)
    raise ExportError(f"Unsupported export: {kind}")


